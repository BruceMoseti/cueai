#!/usr/bin/env node
/**
 * Build one HTML file that plays the game with no server and no network.
 *
 * The page itself is deliberately unbundled: `web/` is plain ES modules served
 * as static files, which is the whole reason it needs no toolchain. That is also
 * why it cannot be opened from a disk — a module graph over `file://` is refused
 * by the browser, so double-clicking `web/index.html` gets you a blank page.
 * This produces the one artefact that does work that way: the same markup with
 * the stylesheet, the measured figures and every module inlined.
 *
 * It is a concatenation rather than a bundle, which is legal here for reasons
 * that are checked rather than assumed: the imports are all named and static,
 * the graph is acyclic, and no two modules declare the same name at the top
 * level. Any of those stopping being true fails the build with the offending
 * name, instead of producing a file that loads and then misbehaves.
 *
 *   node web/build/standalone.mjs           write play.html
 *   node web/build/standalone.mjs --check    fail if play.html is out of date
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(WEB, "..");
const OUTPUT = join(ROOT, "play.html");
const ENTRY = "main.js";

const IMPORT = /^import\s*\{([\s\S]*?)\}\s*from\s*"\.\/([\w.-]+)";?[ \t]*\n/gm;
const DECLARATION = /^(?:export\s+)?(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

const read = (...parts) => readFileSync(join(WEB, ...parts), "utf8");

/** Modules in the order they must run: every dependency before its importer. */
function moduleOrder(entry) {
  const done = [];
  const visit = (name, stack) => {
    if (done.includes(name)) return;
    if (stack.includes(name)) {
      throw new Error(`import cycle, which a concatenation cannot express: ${[...stack, name].join(" -> ")}`);
    }
    for (const [, , dependency] of read("js", name).matchAll(IMPORT)) {
      visit(dependency, [...stack, name]);
    }
    done.push(name);
  };
  visit(entry, []);
  return done;
}

/**
 * Turn a module into a fragment of the shared scope.
 *
 * Imports become nothing, because the names they ask for are already declared
 * further up the file — except renaming ones (`x as y`), which become the
 * binding they promised.
 */
function flatten(name, source) {
  for (const forbidden of ["import.meta", "import("]) {
    if (source.includes(forbidden)) {
      throw new Error(`${name} uses ${forbidden}, which does not survive inlining`);
    }
  }
  let body = source.replace(IMPORT, (_, names) => {
    const aliases = names
      .split(",")
      .map((entry) => entry.trim().match(/^([A-Za-z_$][\w$]*)\s+as\s+([A-Za-z_$][\w$]*)$/))
      .filter(Boolean)
      .map(([, from, to]) => `const ${to} = ${from};`);
    return aliases.length ? `${aliases.join("\n")}\n` : "";
  });
  body = body.replace(/^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\s)/gm, "");
  return `// ---- web/js/${name} ----\n${body.trim()}\n`;
}

function build() {
  const names = moduleOrder(ENTRY);

  const owners = new Map();
  const fragments = [];
  for (const name of names) {
    const source = read("js", name);
    for (const [, declared] of source.matchAll(DECLARATION)) {
      const existing = owners.get(declared);
      if (existing) {
        throw new Error(
          `${name} and ${existing} both declare "${declared}" at the top level, ` +
            `so they cannot share one scope. Rename one of them.`
        );
      }
      owners.set(declared, name);
    }
    fragments.push(flatten(name, source));
  }

  const script = fragments.join("\n");
  const css = read("css", "style.css");
  // The figures in the prose are fetched from a file the browser will not read
  // over file://, so they travel with the page instead.
  const facts = read("data", "facts.json").trim();

  for (const [what, text, closing] of [
    ["the modules", script, "</script"],
    ["the stylesheet", css, "</style"],
  ]) {
    if (text.includes(closing)) throw new Error(`${what} contains ${closing}>, which would end the tag early`);
  }

  const html = read("index.html")
    .replace(
      /^ *<link rel="stylesheet" href="css\/style\.css" \/>\n/m,
      `    <style>\n${css}\n    </style>\n`
    )
    .replace(
      /^ *<script type="module" src="js\/main\.js"><\/script>\n/m,
      `    <script type="module">\n      window.__measuredFacts = ${facts};\n${script}\n    </script>\n`
    )
    .replace(
      /^<!doctype html>\n/,
      "<!doctype html>\n<!-- Generated by web/build/standalone.mjs from web/. Edit that, not this. -->\n"
    );

  for (const [what, marker] of [
    ["the stylesheet", "<style>"],
    ["the modules", "window.__measuredFacts"],
    ["the generated-file notice", "standalone.mjs"],
  ]) {
    if (!html.includes(marker)) throw new Error(`${what} was not inlined; web/index.html must have changed shape`);
  }
  return { html, modules: names };
}

const { html, modules } = build();
const kb = (text) => `${Math.round(text.length / 1024)} kB`;

if (process.argv.includes("--check")) {
  let committed;
  try {
    committed = readFileSync(OUTPUT, "utf8");
  } catch {
    console.error("play.html is missing. Run: make standalone");
    process.exit(1);
  }
  if (committed !== html) {
    console.error("play.html is out of date with web/. Run: make standalone");
    process.exit(1);
  }
  console.log(`play.html matches web/ (${modules.length} modules, ${kb(html)})`);
} else {
  writeFileSync(OUTPUT, html);
  console.log(`wrote play.html: ${modules.join(", ")} inlined, ${kb(html)}`);
}
